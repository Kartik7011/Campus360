import { today, uid, upsert, type Op } from './ops'
import type { IssuedDocument, IssuedDocumentKind, Student } from './types'

export const verifyUrl = (serial: string) =>
  `${window.location.origin}${window.location.pathname}#/verify/${serial}`

const prefixes: Record<IssuedDocumentKind, string> = {
  'Grade sheet': 'GS',
  'Consolidated marks statement': 'CM',
  'Fee receipt': 'RC',
  'Credit note': 'CN',
  'Hall ticket': 'HT',
  'Fee certificate': 'FC',
}

// A new serial for every download, recorded so the QR code can be verified (FR-DOC-02).
export function issueDocument(
  student: Student,
  kind: IssuedDocumentKind,
  title: string,
  ref: string,
  now = new Date(),
): { doc: IssuedDocument; op: Op } {
  const doc: IssuedDocument = {
    id: uid('doc'),
    serial: `C360-${prefixes[kind]}-${crypto.randomUUID().replace(/-/g, '').slice(0, 8).toUpperCase()}`,
    studentId: student.id,
    kind,
    title,
    ref,
    issuedOn: today(now),
  }
  return { doc, op: upsert('issuedDocuments', doc) }
}

export interface PdfTable {
  title?: string
  head: string[]
  widths: number[]
  rows: string[][]
}

export interface PdfContent {
  title: string
  serial: string
  student: Student
  facts: [string, string][]
  tables: PdfTable[]
  notes?: string[]
  // provisional self-service copies carry a watermark (FR-DOC-03)
  provisional?: boolean
}

// jsPDF's built-in fonts have no ₹ sign
export const inr = (amount: number) => `Rs. ${amount.toLocaleString('en-IN')}`

export async function downloadPdf(content: PdfContent, filename: string) {
  ;(await buildPdf(content)).save(filename)
}

export async function buildPdf(content: PdfContent) {
  const [{ jsPDF }, QRCode] = await Promise.all([import('jspdf'), import('qrcode')])
  const pdf = new jsPDF({ unit: 'mm', format: 'a4' })
  const qr = await QRCode.toDataURL(verifyUrl(content.serial), { margin: 0, width: 240 })
  const left = 16
  const right = 194
  let y = 18

  const watermark = () => {
    if (!content.provisional) return
    pdf.saveGraphicsState()
    pdf.setGState(pdf.GState({ opacity: 0.08 }))
    pdf.setFont('helvetica', 'bold')
    pdf.setFontSize(42)
    pdf.text('PROVISIONAL - FOR INFORMATION ONLY', 105, 170, { align: 'center', angle: 35 })
    pdf.restoreGraphicsState()
  }
  const newPage = () => {
    pdf.addPage()
    watermark()
    y = 18
  }

  watermark()
  pdf.setFont('helvetica', 'bold')
  pdf.setFontSize(9)
  pdf.setTextColor(90)
  pdf.text('CAMPUS360 · Generated from university records', left, y)
  pdf.addImage(qr, 'PNG', right - 28, 10, 28, 28)
  pdf.setFontSize(7)
  pdf.text('Scan to verify', right - 14, 41, { align: 'center' })
  y += 9
  pdf.setTextColor(15)
  pdf.setFontSize(17)
  pdf.text(content.title, left, y)
  y += 7
  pdf.setFont('helvetica', 'normal')
  pdf.setFontSize(9)
  pdf.setTextColor(90)
  pdf.text(`Serial ${content.serial} · issued ${new Date().toLocaleDateString('en-IN')}`, left, y)
  y += 10

  pdf.setTextColor(15)
  const facts: [string, string][] = [
    ['Name', content.student.name],
    ['Enrolment no.', content.student.enrolmentNo],
    ['Programme', `${content.student.program} ${content.student.branch}`],
    ...content.facts,
  ]
  facts.forEach(([label, value], index) => {
    const x = index % 2 === 0 ? left : 105
    if (index % 2 === 0 && index > 0) y += 6
    pdf.setFont('helvetica', 'bold')
    pdf.text(`${label}:`, x, y)
    pdf.setFont('helvetica', 'normal')
    pdf.text(String(value), x + 28, y)
  })
  y += 10

  for (const table of content.tables) {
    if (y > 250) newPage()
    if (table.title) {
      pdf.setFont('helvetica', 'bold')
      pdf.setFontSize(11)
      pdf.text(table.title, left, y)
      y += 6
    }
    pdf.setFontSize(8.5)
    const drawHead = () => {
      pdf.setFillColor(235, 237, 240)
      pdf.rect(left, y - 4.2, right - left, 6.5, 'F')
      pdf.setFont('helvetica', 'bold')
      let x = left + 1.5
      table.head.forEach((cell, index) => {
        pdf.text(cell, x, y)
        x += table.widths[index]
      })
      y += 6
      pdf.setFont('helvetica', 'normal')
    }
    drawHead()
    for (const row of table.rows) {
      const lines = row.map((cell, index) => pdf.splitTextToSize(cell, table.widths[index] - 3) as string[])
      const height = Math.max(...lines.map((cell) => cell.length)) * 4 + 1.5
      if (y + height > 282) {
        newPage()
        drawHead()
      }
      let x = left + 1.5
      lines.forEach((cell, index) => {
        pdf.text(cell, x, y)
        x += table.widths[index]
      })
      y += height
      pdf.setDrawColor(230)
      pdf.line(left, y - 3.5, right, y - 3.5)
    }
    y += 6
  }

  pdf.setFontSize(8)
  pdf.setTextColor(90)
  for (const note of [
    ...(content.notes ?? []),
    content.provisional
      ? 'Provisional copy generated by the student. The signed document is issued by the Controller of Examinations.'
      : '',
    `Verify at ${verifyUrl(content.serial)}`,
  ].filter(Boolean)) {
    const lines = pdf.splitTextToSize(note, right - left) as string[]
    if (y + lines.length * 4 > 285) newPage()
    pdf.text(lines, left, y)
    y += lines.length * 4 + 1
  }
  return pdf
}
