// Writes supabase/seed.sql from src/data.ts, so the sample data has one source.
// Run with: npm run seed:sql. The output can be re-run: existing rows are updated, not duplicated.
import { writeFileSync } from 'node:fs'
import { TABLES, toRow } from '../src/api'
import { seedData } from '../src/data'
import { policy } from '../src/policy'
import type { CollectionKey } from '../src/types'

// columns stored as jsonb; every other array is a Postgres array (text[] or int[])
const JSON_COLUMNS = new Set([
  'components',
  'target',
  'entry1',
  'entry2',
  'file',
  'files',
  'messages',
  'allocations',
  'criteria',
])

function literal(value: unknown, column = ''): string {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (JSON_COLUMNS.has(column)) return `${literal(JSON.stringify(value))}::jsonb`
  if (Array.isArray(value)) {
    // Postgres array literal, e.g. '{"React","Node.js"}'; the column type does the cast
    const items = value.map((item) => `"${String(item).replace(/["\\]/g, '\\$&')}"`)
    return literal(`{${items.join(',')}}`)
  }
  return `'${String(value).replace(/'/g, "''")}'`
}

function upserts(table: string, items: object[]) {
  return items.map((item) => {
    const row = toRow(item)
    const columns = Object.keys(row)
    const updates = columns
      .filter((column) => column !== 'id')
      .map((column) => `"${column}" = excluded."${column}"`)
    return (
      `insert into ${table} (${columns.map((column) => `"${column}"`).join(', ')}) ` +
      `values (${columns.map((column) => literal(row[column], column)).join(', ')}) ` +
      `on conflict (id) do update set ${updates.join(', ')};`
    )
  })
}

const feeRates: [string, number][] = [
  ['Back exam', policy.examFees.Back],
  ['Special exam', policy.examFees.Special],
  ...Object.entries(policy.recheck.fees),
  ...Object.entries(policy.documentFees).map(
    ([kind, amount]) => [`Document:${kind}`, amount] as [string, number],
  ),
]

const sql = [
  '-- Generated by scripts/make-seed.ts from src/data.ts. Do not edit by hand.',
  '-- Sample rows from earlier versions of the seed that no longer exist:',
  "delete from notices where id in ('notice-1', 'notice-3', 'notice-4');",
  "delete from applications where id in ('application-kartik-northstar', 'application-shreyansh-orbit');",
  '',
  ...feeRates.map(
    ([head, amount]) =>
      `insert into fee_rates (head, amount) values (${literal(head)}, ${amount}) on conflict (head) do update set amount = excluded.amount;`,
  ),
  ...(Object.keys(TABLES) as CollectionKey[]).flatMap((key) =>
    upserts(TABLES[key], seedData[key] as object[]),
  ),
  '',
  '-- Links accounts already created in Supabase Auth to their role, matching on email.',
  '-- Accounts created later are linked automatically (link_profile trigger).',
  'insert into profiles (id, role, staff_id)',
  '  select u.id, s.role, s.id from auth.users u join staff s on lower(s.email) = lower(u.email)',
  '  on conflict (id) do update set role = excluded.role, staff_id = excluded.staff_id, student_id = null;',
  'insert into profiles (id, role, student_id)',
  "  select u.id, 'student', s.id from auth.users u join students s on lower(s.email) = lower(u.email)",
  '  on conflict (id) do nothing;',
  'insert into profiles (id, role, student_id)',
  "  select u.id, 'parent', c.student_id from auth.users u join consents c on lower(c.parent_email) = lower(u.email)",
  '  on conflict (id) do nothing;',
  '',
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('Wrote supabase/seed.sql')
