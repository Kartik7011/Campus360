// Writes supabase/seed.sql from src/data.ts, so the sample data has one source.
// Run with: npm run seed:sql
import { writeFileSync } from 'node:fs'
import { toRow } from '../src/api'
import { seedData } from '../src/data'

const ADMIN_EMAIL = 'admin@galgotiasuniversity.ac.in'

function literal(value: unknown): string {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (Array.isArray(value)) {
    // Postgres array literal, e.g. '{"React","Node.js"}'; the column type does the cast
    const items = value.map((item) => `"${String(item).replace(/["\\]/g, '\\$&')}"`)
    return literal(`{${items.join(',')}}`)
  }
  return `'${String(value).replace(/'/g, "''")}'`
}

function inserts(table: string, items: object[]) {
  return items.map((item) => {
    const row = toRow(item)
    return `insert into ${table} (${Object.keys(row).join(', ')}) values (${Object.values(row).map(literal).join(', ')});`
  })
}

const sql = [
  '-- Generated by scripts/make-seed.ts from src/data.ts. Do not edit by hand.',
  ...inserts('students', seedData.students),
  ...inserts('mentors', [seedData.mentor]),
  ...inserts('notices', seedData.notices),
  ...inserts('companies', seedData.companies),
  ...inserts('opportunities', seedData.opportunities),
  ...inserts('applications', seedData.applications),
  ...inserts('recheck_requests', seedData.rechecks),
  ...inserts('resumes', seedData.resumes),
  '',
  '-- Links accounts created in Supabase Auth (Authentication > Users) to their role, matching on email.',
  'insert into profiles (id, role, student_id)',
  "  select u.id, 'student', s.id from auth.users u join students s on lower(s.email) = lower(u.email)",
  '  on conflict (id) do nothing;',
  `insert into profiles (id, role) select id, 'admin' from auth.users where lower(email) = ${literal(ADMIN_EMAIL)}`,
  '  on conflict (id) do nothing;',
  '',
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('Wrote supabase/seed.sql')
